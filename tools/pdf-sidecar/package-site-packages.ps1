# Prune site-packages redundancy, zip it, and produce SHA-256 hash for OSS upload.
# Usage: pwsh -File tools\pdf-sidecar\package-site-packages.ps1
# Output: tools\pdf-sidecar\dist\v0.5.13-1\site-packages.zip + site-packages.sha256

$ErrorActionPreference = "Stop"

$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$root = Resolve-Path (Join-Path $scriptDir "..\..")
$src  = Join-Path $root "src-tauri\binaries\pdfconv\python\Lib\site-packages"
$dist = Join-Path $scriptDir "dist\v0.5.13-1"
$stage = Join-Path $dist "stage"
$zipPath = Join-Path $dist "site-packages.zip"
$hashPath = Join-Path $dist "site-packages.sha256"

if (-not (Test-Path $src)) { throw "site-packages not found: $src" }

if (Test-Path $dist) { Remove-Item $dist -Recurse -Force }
New-Item -ItemType Directory -Path $stage -Force | Out-Null

Write-Host "1/4 Copying site-packages to stage (excluding __pycache__/*.pyc)..."
& robocopy $src $stage /E /XD __pycache__ /XF *.pyc *.pyo | Out-Null
if ($LASTEXITCODE -ge 8) { throw "robocopy failed, code $LASTEXITCODE" }

Write-Host "2/4 Pruning runtime-unused redundancy..."

# 2.1 OpenCV cascade classifiers (keep __init__.py)
Get-ChildItem (Join-Path $stage "cv2\data") -Filter "haarcascade_*.xml" -ErrorAction SilentlyContinue |
    Remove-Item -Force

# 2.2 pymupdf dev headers / import libs
$devel = Join-Path $stage "pymupdf\mupdf-devel"
if (Test-Path $devel) { Remove-Item $devel -Recurse -Force }

# 2.3 numpy tests directories
Get-ChildItem (Join-Path $stage "numpy") -Recurse -Directory -Filter "tests" -ErrorAction SilentlyContinue |
    Remove-Item -Recurse -Force

# 2.4 CLI entry exes and man pages
$bin = Join-Path $stage "bin"
if (Test-Path $bin) { Remove-Item $bin -Recurse -Force }
$share = Join-Path $stage "share"
if (Test-Path $share) { Remove-Item $share -Recurse -Force }

# 2.5 Optional: fontTools *.c sources (kept by default; uncomment to save ~5.9MB after regression)
# Get-ChildItem (Join-Path $stage "fontTools") -Recurse -File -Filter "*.c" | Remove-Item -Force

Write-Host "3/4 Compressing to zip (flat layout, no outer folder)..."
Add-Type -AssemblyName System.IO.Compression.FileSystem
if (Test-Path $zipPath) { Remove-Item $zipPath -Force }
[System.IO.Compression.ZipFile]::CreateFromDirectory($stage, $zipPath,
    [System.IO.Compression.CompressionLevel]::Optimal, $false)

Remove-Item $stage -Recurse -Force

Write-Host "4/4 Computing SHA-256..."
$hash = (Get-FileHash $zipPath -Algorithm SHA256).Hash.ToLower()
[IO.File]::WriteAllText($hashPath, $hash, (New-Object Text.UTF8Encoding($false)))

$sizeMB = [math]::Round((Get-Item $zipPath).Length / 1MB, 1)
Write-Host ""
Write-Host "Done:"
Write-Host "  zip   : $zipPath"
Write-Host "  size  : $sizeMB MB"
Write-Host "  sha256: $hash"
Write-Host "  hash  : $hashPath"
Write-Host ""
Write-Host "Next: upload site-packages.zip to OSS /pdfconv/v0.5.13-1/, then send back"
Write-Host "      the zip HTTPS URL and the sha256 above."
